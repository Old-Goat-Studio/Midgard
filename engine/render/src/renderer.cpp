MeshId Renderer::upload_mesh(const MeshData& mesh) {
    Impl& r = *impl_;
    r.meshes.push_back({});
    const auto id = static_cast<MeshId>(r.meshes.size() - 1);
    replace_mesh(id, mesh);
    return id;
}

void Renderer::replace_mesh(MeshId id, const MeshData& mesh) {
    Impl& r = *impl_;
    if (id >= r.meshes.size()) throw RenderError("replace_mesh: no such mesh");
    GpuMesh& old = r.meshes[id];
    if (old.vertices.buffer) {
        vkDeviceWaitIdle(r.device);
        r.destroy_buffer(old.vertices);
        r.destroy_buffer(old.indices);
    }
    GpuMesh gpu;
    const VkDeviceSize vbytes = mesh.vertices.size() * sizeof(Vertex);
    const VkDeviceSize ibytes = mesh.indices.size() * sizeof(uint32_t);
    // Small static meshes live in host-visible memory for now; a staging upload to
    // device-local memory replaces this when real asset sizes arrive.
    gpu.vertices = r.create_buffer(vbytes, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, false);
    gpu.indices = r.create_buffer(ibytes, VK_BUFFER_USAGE_INDEX_BUFFER_BIT, false);
    std::memcpy(gpu.vertices.mapped, mesh.vertices.data(), vbytes);
    std::memcpy(gpu.indices.mapped, mesh.indices.data(), ibytes);
    vmaFlushAllocation(r.allocator, gpu.vertices.allocation, 0, VK_WHOLE_SIZE);
    vmaFlushAllocation(r.allocator, gpu.indices.allocation, 0, VK_WHOLE_SIZE);
    gpu.index_count = static_cast<uint32_t>(mesh.indices.size());
    r.meshes[id] = gpu;
}

bool Renderer::render_frame(const Camera& camera, const Light& light,
                            std::span<const DrawItem> draws, const glm::vec4& clear_color) {
    Impl& r = *impl_;
    Impl::Frame& f = r.frames[r.frame_index];
    check(vkWaitForFences(r.device, 1, &f.fence, VK_TRUE, UINT64_MAX), "Waiting for a frame");

    uint32_t image = 0;
    if (!r.offscreen) {
        const VkResult acquired = vkAcquireNextImageKHR(r.device, r.swapchain, UINT64_MAX,
                                                        f.image_ready, VK_NULL_HANDLE, &image);
        if (acquired == VK_ERROR_OUT_OF_DATE_KHR) {
            r.recreate_target();
            return false;
        }
        if (acquired == VK_ERROR_SURFACE_LOST_KHR) {
            r.recreate_surface();
            return false;
        }
        if (acquired != VK_SUBOPTIMAL_KHR) check(acquired, "Acquiring a swapchain image");
    }
    check(vkResetFences(r.device, 1, &f.fence), "Resetting a fence");

    FrameData data{};
    data.view_proj = camera.projection * camera.view;
    data.up = glm::vec4(glm::normalize(light.up), 0.0f);
    data.sun_direction = glm::vec4(light.direction, 0.0f);
    data.sun_color = glm::vec4(to_linear(light.color) * light.intensity, 1.0f);
    data.ambient_sky = glm::vec4(to_linear(light.ambient), 1.0f);
    data.ambient_ground = glm::vec4(to_linear(light.ambient_ground), 1.0f);
    const int local = std::min<int>(static_cast<int>(light.local.size()), kMaxLocalLights);
    data.counts = glm::ivec4(local, 0, 0, 0);
    for (int i = 0; i < local; ++i) {
        const LocalLight& l = light.local[size_t(i)];
        GpuLocalLight& g = data.lights[i];
        g.position_range = glm::vec4(l.position, std::max(l.range, 1e-3f));
        g.color = glm::vec4(to_linear(l.color) * l.intensity, l.spot ? 1.0f : 0.0f);
        const float outer = glm::radians(std::max(l.outer_angle, l.inner_angle + 0.01f));
        g.direction = glm::vec4(glm::normalize(l.direction), std::cos(outer));
        g.cone = glm::vec4(std::cos(glm::radians(l.inner_angle)), 0.0f, 0.0f, 0.0f);
    }
    std::memcpy(f.ubo.mapped, &data, sizeof(data));
    vmaFlushAllocation(r.allocator, f.ubo.allocation, 0, VK_WHOLE_SIZE);

    r.prepare_overlay(f);
    check(vkResetCommandBuffer(f.cmd, 0), "Resetting a command buffer");
    r.record(f.cmd, r.framebuffers[r.offscreen ? 0 : image], draws, clear_color, f.set, f);

    VkPipelineStageFlags wait_stage = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
    VkSubmitInfo submit{VK_STRUCTURE_TYPE_SUBMIT_INFO};
    submit.commandBufferCount = 1;
    submit.pCommandBuffers = &f.cmd;
    if (!r.offscreen) {
        submit.waitSemaphoreCount = 1;
        submit.pWaitSemaphores = &f.image_ready;
        submit.pWaitDstStageMask = &wait_stage;
        submit.signalSemaphoreCount = 1;
        submit.pSignalSemaphores = &r.render_done[image];
    }
    check(vkQueueSubmit(r.queue, 1, &submit, f.fence), "Submitting a frame");

    if (r.offscreen) {
        check(vkWaitForFences(r.device, 1, &f.fence, VK_TRUE, UINT64_MAX), "Waiting for a frame");
    } else {
        VkPresentInfoKHR present{VK_STRUCTURE_TYPE_PRESENT_INFO_KHR};
        present.waitSemaphoreCount = 1;
        present.pWaitSemaphores = &r.render_done[image];
        present.swapchainCount = 1;
        present.pSwapchains = &r.swapchain;
        present.pImageIndices = &image;
        const VkResult presented = vkQueuePresentKHR(r.queue, &present);
        if (presented == VK_ERROR_OUT_OF_DATE_KHR || presented == VK_SUBOPTIMAL_KHR)
            r.recreate_target();
        else if (presented == VK_ERROR_SURFACE_LOST_KHR)
            r.recreate_surface();
        else
            check(presented, "Presenting a frame");
    }
    r.frame_index = (r.frame_index + 1) % kFramesInFlight;
    return true;
}

